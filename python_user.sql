-- product
-- product_id(varchar2(10)), product_name(100), stock_qty(10), unit_price(10), supply_date(date), supply_qty(10)
-- fk 주기
-- check stock_qty 0 이상이어야 한다
-- unit_price 0 보다 커야 한다.
CREATE TABLE product(
	product_id varchar2(20) NOT NULL,
	product_name varchar2(100) NOT NULL,
	stock_qty number(10) DEFAULT 0,
	unit_price number(10) NOT NULL,
	supply_date DATE DEFAULT SYSDATE,
	supply_qty number(10) NOT NULL,
	CONSTRAINT PK_product PRIMARY KEY (product_id),
	CONSTRAINT CK_product_STOCK CHECK (stock_qty > 0),
	CONSTRAINT CK_product_PRICE CHECK (unit_price > 0)
);
