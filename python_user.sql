-- 가계부 기록 테이블(transactions)
-- tx_id : number, 자동증가, pk
-- tx_type : 수입 or 지출
-- amount : 금액
-- memo : 내역
-- reg_date : '2026-08-01'


CREATE TABLE transactions(
	tx_id NUMBER(10) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	tx_type varchar2(10) NOT NULL,
	amount number(10) NOT NULL,
	memo varchar2(2000),
	reg_date varchar2(20)
);

