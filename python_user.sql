-- 회원(hanbit_member)
-- member_id(varchar2(20)) pk, password(varchar2(20)), name(varchar2(20)), age(number(3)), grade(varchar2(10)), points(number(10))
-- grade는 default 값 : REGULAR, points default 0
-- age check 0보다 커야 한다
-- points check 0 이상이어야 한다
CREATE TABLE hanbit_member(
	member_id varchar2(20) NOT NULL,
	password varchar2(20) NOT NULL,
	name varchar2(20) NOT NULL,
	age number(3),
	grade varchar2(10) DEFAULT 'REGULAR',
	points number(10),
	CONSTRAINT PK_hanbit_member PRIMARY KEY (member_id),
	CONSTRAINT CK_member_AGE CHECK (age > 0),
	CONSTRAINT CK_member_POINTS CHECK (points >= 0)
);



-- 제조업체(manufacturer)
